/// Maps a MacroButton (from a captured mouse button event) to evdev key for re-emission.
pub fn evdev_button_from_code(code: u16) -> Option<crate::input::types::MacroButton> {
    use crate::input::types::MacroButton;
    Some(match Key(code) {
        Key::BTN_LEFT => MacroButton::Left,
        Key::BTN_RIGHT => MacroButton::Right,
        Key::BTN_MIDDLE => MacroButton::Middle,
        Key::BTN_BACK | Key::BTN_SIDE => MacroButton::Back,
        Key::BTN_FORWARD | Key::BTN_EXTRA => MacroButton::Forward,
        _ => return None,
    })
}

