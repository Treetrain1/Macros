/// Maps a MacroButton to the corresponding evdev Key code for emission.
pub fn macro_button_to_evdev(button: &crate::input::types::MacroButton) -> Option<Key> {
    use crate::input::types::MacroButton;
    Some(match button {
        MacroButton::Left => Key::BTN_LEFT,
        MacroButton::Right => Key::BTN_RIGHT,
        MacroButton::Middle => Key::BTN_MIDDLE,
        MacroButton::Back => Key::BTN_BACK,
        MacroButton::Forward => Key::BTN_FORWARD,
        MacroButton::Other(n) => Key(*n as u16),
        // Scroll variants are emitted as REL_WHEEL, not KEY events
        MacroButton::ScrollUp
        | MacroButton::ScrollDown
        | MacroButton::ScrollLeft
        | MacroButton::ScrollRight => return None,
    })
}

